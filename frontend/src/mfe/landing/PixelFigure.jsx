// Dense pixel-dot figures for marketing stats — heavy/bold 5×7 bitmaps.
const GLYPHS = {
  "0": ["01110", "11111", "11011", "11011", "11011", "11111", "01110"],
  "1": ["01100", "11100", "01100", "01100", "01100", "01100", "11110"],
  "2": ["01110", "11111", "00011", "01110", "11100", "11000", "11111"],
  "3": ["01110", "11111", "00011", "01110", "00011", "11111", "01110"],
  "4": ["00110", "01110", "11010", "11010", "11111", "00110", "00110"],
  "5": ["11111", "11000", "11110", "01111", "00011", "11111", "01110"],
  "6": ["01110", "11100", "11000", "11110", "11011", "11111", "01110"],
  "7": ["11111", "11111", "00011", "00110", "01100", "01100", "01100"],
  "8": ["01110", "11111", "11011", "01110", "11011", "11111", "01110"],
  "9": ["01110", "11111", "11011", "01111", "00011", "00111", "01110"],
  $: ["00100", "01110", "11111", "11100", "01110", "00111", "11111"],
  T: ["11111", "11111", "01110", "01110", "01110", "01110", "01110"],
  "%": ["11011", "11011", "00110", "01100", "01100", "11011", "11011"],
  "<": ["00011", "00110", "01100", "11000", "01100", "00110", "00011"],
  "–": ["00000", "00000", "11111", "11111", "00000", "00000", "00000"],
  "-": ["00000", "00000", "11111", "11111", "00000", "00000", "00000"],
  " ": ["00000", "00000", "00000", "00000", "00000", "00000", "00000"],
};

export default function PixelFigure({ value, className = "" }) {
  const chars = [...String(value)];
  return (
    <div className={`landing-pixel-figure ${className}`.trim()} aria-label={value}>
      {chars.map((ch, i) => {
        const rows = GLYPHS[ch] || GLYPHS[" "];
        return (
          <span key={`${ch}-${i}`} className="landing-pixel-glyph" aria-hidden="true">
            {rows.flatMap((row, y) =>
              [...row].map((bit, x) => (
                <i
                  key={`${y}-${x}`}
                  className={bit === "1" ? "is-on" : undefined}
                  style={{
                    gridColumn: x + 1,
                    gridRow: y + 1,
                    "--px": x,
                    "--py": y,
                  }}
                />
              )),
            )}
          </span>
        );
      })}
    </div>
  );
}
